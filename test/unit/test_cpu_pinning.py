"""CPU affinity is optional and works with existing xl templates."""

from pathlib import Path
from types import SimpleNamespace

import pytest

from drakrun.lib import vm
from drakrun.lib.install_info import InstallInfo


@pytest.fixture
def render(tmp_path, monkeypatch):
    monkeypatch.setattr(vm, "CONFIGS_DIR", tmp_path)
    monkeypatch.setattr(vm, "get_storage_backend", lambda _: None)

    def generate(template_text, cpus=None, vm_id=1):
        template = tmp_path / "cfg.template"
        template.write_text(template_text)
        info = InstallInfo(
            storage_backend="qcow2",
            disk_size="12G",
            vnc_passwd="test",
            vcpus=4,
            memory=5120,
            cpus=cpus,
            xl_cfg_template=template,
        )
        machine = vm.VirtualMachine(vm_id, info, None)
        machine._network_info = SimpleNamespace(bridge_name=f"drak{vm_id}")
        return machine._generate_vm_conf(["file:disk,hda,w"]).read_text()

    return generate


def test_existing_windows_config_unchanged_without_pinning(render):
    template = (Path(vm.__file__).parents[1] / "data" / "cfg.template").read_text()
    expected = template
    for key, value in {
        "VM_NAME": "vm-1",
        "VM_ID": "1",
        "DISKS": '"file:disk,hda,w"',
        "VNC_PORT": "6401",
        "VCPUS": "4",
        "MEMORY": "5120",
        "VNC_PASS": "test",
        "BRIDGE_NAME": "drak1",
        "ON_REBOOT": "destroy",
    }.items():
        expected = expected.replace("{{ " + key + " }}", value)
    assert render(template) == (
        "# Autogenerated, don't edit this file directly!\n"
        "# Instead please edit /etc/drakrun/cfg.template\n" + expected
    )


@pytest.mark.parametrize("cpus", ["8-11", "12-15", "8,10-11", "8"])
def test_pinning_appended_without_template_change(render, cpus):
    cfg = render('name = "{{ VM_NAME }}"\n', cpus)
    assert cfg.endswith(f'\ncpus = "{cpus}"\n')


def test_pinning_uses_template_placeholder(render):
    cfg = render('name = "{{ VM_NAME }}"\ncpus = "{{ CPUS }}"\n', "12-15", vm_id=2)
    assert cfg.endswith('name = "vm-2"\ncpus = "12-15"\n')
    assert cfg.count("cpus =") == 1


def test_unset_pinning_removes_placeholder_line(render):
    cfg = render('name = "{{ VM_NAME }}"\ncpus = "{{ CPUS }}"\n')
    assert cfg.endswith('name = "vm-1"\n')
    assert "cpus =" not in cfg
    assert "{{ CPUS }}" not in cfg


@pytest.mark.parametrize("cpus", ["", '8"\nmemory=1', "-1", "8;9", "all"])
def test_invalid_cpu_lists_rejected(cpus):
    with pytest.raises(ValueError):
        InstallInfo(
            storage_backend="qcow2",
            disk_size="12G",
            vnc_passwd="test",
            vcpus=4,
            memory=4096,
            cpus=cpus,
        )
